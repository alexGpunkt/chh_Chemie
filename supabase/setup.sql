-- ------------------------------------------------------------
-- Lehrkraftseite: Bewertungsuebersicht
--
-- Beide Wege fuehren zu einer Zahl zwischen 0 und 1, die dann nach der
-- Berliner Sekundarstufenskala in eine Note umgesetzt wird:
--
--   note         Mittel aller gewerteten Laeufe.
--   fortschritt  Der Stand der zweiten Haelfte, zuzueglich der Verbesserung
--                gegenueber der ersten. Wer schwach beginnt und stark
--                endet, wird nach dem Ende bewertet - wer gleich stark
--                bleibt, verliert dadurch nichts.
--
-- Die Note wird hier berechnet und nicht im Dashboard: Eine Notenskala
-- gehoert an eine Stelle, nicht in jeden Client.
-- ------------------------------------------------------------
create or replace function public.chemie710_warmup_uebersicht(
  p_klasse text default null,
  p_tage integer default 180
)
returns table (
  student_id uuid,
  name text,
  klasse text,
  bewertungsart text,
  laeufe integer,
  aufgaben integer,
  richtig integer,
  quote_gesamt numeric,
  quote_frueh numeric,
  quote_spaet numeric,
  punktwert numeric,
  note smallint,
  letzter_lauf date,
  schwache_kategorien text[]
)
language sql
stable
security definer
set search_path = public
as $fn$
  with fenster as (
    select w.*,
           row_number() over (partition by w.student_id order by w.datum, w.id) as lfd,
           count(*) over (partition by w.student_id) as gesamt
      from public.chemie710_warmup_ergebnisse w
     where w.gewertet
       and w.datum >= (now() - make_interval(days => greatest(coalesce(p_tage, 180), 1)))::date
  ),
  je_person as (
    select f.student_id,
           count(*)::integer as laeufe,
           sum(f.aufgaben)::integer as aufgaben,
           sum(f.richtig)::integer as richtig,
           round(sum(f.richtig)::numeric / nullif(sum(f.aufgaben), 0), 3) as quote_gesamt,
           round(sum(f.richtig) filter (where f.lfd <= ceil(f.gesamt / 2.0))::numeric
                 / nullif(sum(f.aufgaben) filter (where f.lfd <= ceil(f.gesamt / 2.0)), 0), 3)
             as quote_frueh,
           round(sum(f.richtig) filter (where f.lfd > ceil(f.gesamt / 2.0))::numeric
                 / nullif(sum(f.aufgaben) filter (where f.lfd > ceil(f.gesamt / 2.0)), 0), 3)
             as quote_spaet,
           max(f.datum) as letzter_lauf,
           (select array_agg(distinct k)
              from fenster g, unnest(g.kategorien) as k
             where g.student_id = f.student_id
               and g.richtig::numeric / g.aufgaben < 0.6) as schwache_kategorien
      from fenster f
     group by f.student_id
  ),
  bewertet as (
    select s.id as student_id,
           s.display_name as name,
           s.class_code as klasse,
           s.bewertungsart,
           coalesce(p.laeufe, 0) as laeufe,
           coalesce(p.aufgaben, 0) as aufgaben,
           coalesce(p.richtig, 0) as richtig,
           p.quote_gesamt,
           p.quote_frueh,
           p.quote_spaet,
           case
             when p.laeufe is null then null
             when s.bewertungsart = 'fortschritt' then
               least(1.0, coalesce(p.quote_spaet, p.quote_gesamt)
                          + greatest(0, coalesce(p.quote_spaet, 0) - coalesce(p.quote_frueh, 0)))
             else p.quote_gesamt
           end as punktwert,
           p.letzter_lauf,
           coalesce(p.schwache_kategorien, array[]::text[]) as schwache_kategorien
      from public.chemie710_students s
      left join je_person p on p.student_id = s.id
     where s.active
       and (p_klasse is null or s.class_code = p_klasse)
  )
  select b.student_id, b.name, b.klasse, b.bewertungsart,
         b.laeufe, b.aufgaben, b.richtig,
         b.quote_gesamt, b.quote_frueh, b.quote_spaet,
         round(b.punktwert, 3),
         case
           when b.punktwert is null then null
           when b.punktwert >= 0.92 then 1
           when b.punktwert >= 0.81 then 2
           when b.punktwert >= 0.67 then 3
           when b.punktwert >= 0.50 then 4
           when b.punktwert >= 0.30 then 5
           else 6
         end::smallint,
         b.letzter_lauf,
         b.schwache_kategorien
    from bewertet b
   order by b.name;
$fn$;

