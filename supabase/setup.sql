-- ------------------------------------------------------------
-- Was darf dieses Kind gerade?  (Aufruf mit Schueler-Token)
-- ------------------------------------------------------------
create or replace function public.chemie710_lernmodus()
returns table (
  modus text,
  gilt_bis timestamptz,
  freigegeben text[],
  lernzeit_heute integer
)
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  kind uuid;
  aktuell public.chemie710_unterricht%rowtype;
begin
  kind := public.chemie710_token_student();
  if kind is null then
    raise exception 'Kein gueltiges Schueler-Sitzungstoken.' using errcode = '42501';
  end if;

  select * into aktuell from public.chemie710_unterricht where id = 1;

  return query select
    -- Abgelaufener Bewertungsmodus gilt nicht mehr. Der Rueckfall ist der
    -- offene Zustand, nicht der gesperrte: Eine vergessene Umschaltung darf
    -- niemanden aussperren.
    case
      when aktuell.modus = 'bewertung'
       and (aktuell.gilt_bis is null or aktuell.gilt_bis > now())
      then 'bewertung'
      else 'uebung'
    end::text,
    aktuell.gilt_bis,
    coalesce((
      select array_agg(f.unit order by f.unit)
      from public.chemie710_freigaben f
      where f.student_id = kind
    ), array[]::text[]),
    coalesce((
      select sum(l.sekunden)::integer
      from public.chemie710_lernzeit l
      where l.student_id = kind
        and l.datum = (now() at time zone 'Europe/Berlin')::date
    ), 0);
end;
$fn$;

revoke all on function public.chemie710_lernmodus() from public;
grant execute on function public.chemie710_lernmodus() to anon, authenticated;


-- ------------------------------------------------------------
-- Aktive Lernzeit melden  (Aufruf mit Schueler-Token)
-- ------------------------------------------------------------
create or replace function public.chemie710_lernzeit_melden(
  p_unit text,
  p_sekunden integer
)
returns integer
language plpgsql
security definer
set search_path = public
as $fn$
declare
  kind uuid;
  zuwachs integer;
begin
  kind := public.chemie710_token_student();
  if kind is null then
    raise exception 'Kein gueltiges Schueler-Sitzungstoken.' using errcode = '42501';
  end if;

  -- Obergrenze je Meldung: Die App meldet alle paar Minuten. Ein groesserer
  -- Wert kaeme entweder von einer sehr langen Offlinephase oder von einem
  -- manipulierten Aufruf. In beiden Faellen ist Deckeln richtiger als
  -- Glauben.
  zuwachs := least(greatest(coalesce(p_sekunden, 0), 0), 900);
  if zuwachs = 0 then
    return 0;
  end if;

  insert into public.chemie710_lernzeit (student_id, unit, sekunden)
  values (kind, coalesce(nullif(trim(p_unit), ''), '—'), zuwachs)
  on conflict (student_id, datum, unit) do update
    set sekunden = public.chemie710_lernzeit.sekunden + excluded.sekunden,
        aktualisiert_at = now();

  return zuwachs;
end;
$fn$;

revoke all on function public.chemie710_lernzeit_melden(text, integer) from public;
grant execute on function public.chemie710_lernzeit_melden(text, integer) to anon, authenticated;


-- ------------------------------------------------------------
-- Lehrkraftseite: Modus umschalten und Einheiten freigeben
-- ------------------------------------------------------------
create or replace function public.chemie710_unterricht_setzen(
  p_modus text,
  p_minuten integer default 90,
  p_klasse text default null
)
returns public.chemie710_unterricht
language plpgsql
security definer
set search_path = public
as $fn$
declare
  ergebnis public.chemie710_unterricht%rowtype;
begin
  if not public.chemie710_ist_lehrkraft() then
    raise exception 'Nur freigeschaltete Lehrkraefte duerfen den Lernmodus umschalten.'
      using errcode = '42501';
  end if;
  if p_modus not in ('uebung', 'bewertung') then
    raise exception 'Unbekannter Modus: %', p_modus;
  end if;

  update public.chemie710_unterricht
     set modus = p_modus,
         gilt_bis = case
           when p_modus = 'bewertung'
           then now() + make_interval(mins => greatest(coalesce(p_minuten, 90), 5))
           else null
         end,
         klasse = p_klasse,
         gesetzt_von = auth.uid(),
         gesetzt_at = now()
   where id = 1
  returning * into ergebnis;

  return ergebnis;
end;
$fn$;

