-- Anmeldung mit Tokenausgabe. Ersetzt chemie710_validate_student_login;
-- die alte Funktion bleibt fuer aeltere Clients bestehen.
create or replace function public.chemie710_student_anmelden(
  p_login_name text,
  p_class_code text,
  p_stunden integer default 12
)
returns table (
  student_id uuid,
  login_name text,
  display_name text,
  class_code text,
  token text,
  gueltig_bis timestamptz
)
language plpgsql
security definer
set search_path = public
as $fn$
declare
  gefunden record;
  neues_token text;
  frist timestamptz;
begin
  select st.id, st.login_name, st.display_name, st.class_code
    into gefunden
  from public.chemie710_students as st
  where lower(st.login_name) = lower(trim(p_login_name))
    and lower(st.class_code) = lower(trim(p_class_code))
    and st.active
  limit 1;

  if gefunden.id is null then
    return;                      -- keine Zeile: Anmeldung abgelehnt
  end if;

  -- Ein Schultag plus Puffer. Laenger als noetig waere ein unnoetiges
  -- Risiko auf einem Geraet, das die naechste Klasse benutzt.
  frist := now() + make_interval(hours => greatest(1, least(24, coalesce(p_stunden, 12))));
  neues_token := encode(gen_random_bytes(32), 'hex');

  insert into public.chemie710_student_tokens (token_hash, student_id, gueltig_bis)
  values (encode(extensions.digest(neues_token, 'sha256'), 'hex'), gefunden.id, frist);

  -- Abgelaufene Token bei Gelegenheit entfernen.
  delete from public.chemie710_student_tokens where gueltig_bis < now() - interval '7 days';

  return query
    select gefunden.id, gefunden.login_name, gefunden.display_name,
           gefunden.class_code, neues_token, frist;
end;
$fn$;

revoke all on function public.chemie710_student_anmelden(text, text, integer) from public;
grant execute on function public.chemie710_student_anmelden(text, text, integer) to anon, authenticated;

