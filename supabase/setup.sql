-- ============================================================
-- Warm-up: Pflicht im Unterricht, Uebung danach  (V31)
--
-- Das Warm-up wiederholt das Grundwissen der zurueckliegenden Unterrichts-
-- reihen. Es hat zwei Betriebsarten, und die haengen am selben Schalter wie
-- alles andere (chemie710_unterricht):
--
--   Uebungsmodus     Freiwillig, so oft wie gewollt. Die Ergebnisse werden
--                    festgehalten, zaehlen aber nicht fuer die Note. Wer
--                    zuhause uebt, soll dabei nichts riskieren.
--   Bewertungsmodus  Verpflichtend vor der Einheit. Genau der erste Lauf
--                    des Tages zaehlt.
--
-- Warum nur der erste Lauf: Sonst waere die Note eine Frage der Anzahl der
-- Versuche. Weitere Laeufe am selben Tag werden gespeichert, aber als
-- Uebung gefuehrt - sie verbessern die Note nicht und verschlechtern sie
-- auch nicht.
-- ============================================================

-- Wonach wird dieses Kind bewertet? Die Entscheidung trifft die Lehrkraft
-- je Person, nicht die Anwendung fuer alle:
--
--   note         Der Durchschnitt der einzelnen Ergebnisse.
--   fortschritt  Die Entwicklung ueber die Zeit. Wer schwach anfaengt und
--                besser wird, soll dafuer nicht mit dem Mittelwert der
--                schwachen Anfaenge bezahlen.
alter table public.chemie710_students
  add column if not exists bewertungsart text not null default 'note';

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'chemie710_students_bewertungsart'
  ) then
    alter table public.chemie710_students
      add constraint chemie710_students_bewertungsart
      check (bewertungsart in ('note', 'fortschritt'));
  end if;
end;
$$;


