-- ============================================================
-- Aufbewahrung und Löschung
-- Siehe DATENSCHUTZ.md. Fristen hier zentral, damit sie nicht in
-- Kommentaren stehen, sondern tatsächlich wirken.
-- ============================================================

-- Rohereignisse: 90 Tage. Fortschritt: ein Schuljahr.
create or replace function public.chemie710_aufraeumen(
  ereignis_tage integer default 90,
  fortschritt_tage integer default 365
)
returns table (tabelle text, geloescht bigint)
language plpgsql
security definer
set search_path = public
as $$
declare
  n_ereignisse bigint;
  n_fortschritt bigint;
  n_token bigint;
  erlaubt boolean := false;
  lauf bigint;
begin
  -- SECURITY DEFINER umgeht RLS. Ein EXECUTE-Recht allein reicht daher
  -- nicht: angemeldete Aufrufer werden zusätzlich gegen die Lehrkraftliste
  -- bzw. den serverseitigen teacher-Claim geprüft. pg_cron/SQL-Administration
  -- läuft ohne auth.uid() und darf die Wartung weiterhin ausführen.
  if auth.role() = 'authenticated' or auth.uid() is not null then
    execute $q$
      select exists (
        select 1 from public.chemie710_teachers t where t.user_id = $1
      ) or coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'teacher', false)
    $q$ into erlaubt using auth.uid();
    if not erlaubt then
      raise exception 'Nur freigeschaltete Lehrkräfte dürfen die Datenbereinigung ausführen.'
        using errcode = '42501';
    end if;
  end if;

  -- Erst den Lauf eröffnen, dann arbeiten: Bricht der Job ab, bleibt eine
  -- Zeile mit erfolg = false stehen. Ein stiller Ausfall wäre sonst von
  -- „läuft, findet aber nichts" nicht zu unterscheiden.
  insert into public.chemie710_wartung_laeufe (ereignis_tage, fortschritt_tage, ausgeloest_von)
  values (
    ereignis_tage,
    fortschritt_tage,
    coalesce(nullif(auth.uid()::text, ''), 'planmaessig')
  )
  returning id into lauf;

  begin
    delete from public.chemie710_events
    where ts < now() - make_interval(days => ereignis_tage);
    get diagnostics n_ereignisse = row_count;

    delete from public.chemie710_progress
    where coalesce(updated_at, ts) < now() - make_interval(days => fortschritt_tage);
    get diagnostics n_fortschritt = row_count;

    -- Abgelaufene Sitzungstoken enthalten keine Lernantworten, sollten aber
    -- ebenfalls nicht unbegrenzt anwachsen.
    begin
      delete from public.chemie710_student_tokens where gueltig_bis < now();
      get diagnostics n_token = row_count;
    exception when undefined_table then
      n_token := 0; -- erster Durchlauf einer älteren Installation
    end;

    -- Lernzeiten sind personenbezogen und unterliegen derselben Frist wie
    -- der Fortschritt. Freigaben bleiben an den Schülerdatensatz gebunden
    -- und verschwinden mit ihm (ON DELETE CASCADE).
    begin
      delete from public.chemie710_lernzeit
      where datum < (now() - make_interval(days => fortschritt_tage))::date;
    exception when undefined_table then
      null; -- ältere Installation ohne Lernzeittabelle
    end;

    -- Warm-up-Ergebnisse sind Bewertungsgrundlage und unterliegen derselben
    -- Frist wie der Fortschritt. Ein Schuljahr passt in 365 Tage; alles
    -- darüber hinaus wird für die Notengebung nicht mehr gebraucht.
    begin
      delete from public.chemie710_warmup_ergebnisse
      where datum < (now() - make_interval(days => fortschritt_tage))::date;
    exception when undefined_table then
      null; -- ältere Installation ohne Warm-up-Tabelle
    end;
  exception when others then
    update public.chemie710_wartung_laeufe
       set beendet_at = now(), erfolg = false, fehler = left(sqlerrm, 500)
     where id = lauf;
    raise;
  end;

  update public.chemie710_wartung_laeufe
     set beendet_at = now(),
         erfolg = true,
         ereignisse = n_ereignisse,
         fortschritt = n_fortschritt,
         tokens = n_token
   where id = lauf;

  -- Das Protokoll selbst darf ebenfalls nicht unbegrenzt wachsen.
  delete from public.chemie710_wartung_laeufe
  where gestartet_at < now() - interval '400 days';

  return query
    select 'chemie710_events'::text, n_ereignisse
    union all
    select 'chemie710_progress'::text, n_fortschritt
    union all
    select 'chemie710_student_tokens'::text, n_token;
end;
$$;

comment on function public.chemie710_aufraeumen is
  'Löscht abgelaufene Ereignisse, Fortschrittssätze und Sitzungstoken. Muss planmäßig '
  'aufgerufen werden (pg_cron oder wöchentlich von Hand) — ohne Aufruf '
  'passiert nichts. Jeder Lauf wird in chemie710_wartung_laeufe protokolliert.';


-- Zustand der Datenpflege für das Dashboard. Bewusst eine Funktion und
-- keine Tabellenabfrage: Die Bewertung „überfällig" gehört an eine Stelle,
-- nicht in jeden Client.
create or replace function public.chemie710_wartung_status()
returns table (
  letzter_lauf timestamptz,
  letzter_erfolg timestamptz,
  erfolg boolean,
  fehler text,
  ereignisse bigint,
  fortschritt bigint,
  tokens bigint,
  tage_seit_erfolg numeric,
  ueberfaellig boolean,
  laeufe_30_tage bigint
)
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  letzter public.chemie710_wartung_laeufe%rowtype;
  erfolgreich timestamptz;
begin
  if not public.chemie710_ist_lehrkraft() then
    raise exception 'Nur freigeschaltete Lehrkräfte dürfen den Wartungsstatus lesen.'
      using errcode = '42501';
  end if;

  select * into letzter from public.chemie710_wartung_laeufe
   order by gestartet_at desc limit 1;

  select max(w.gestartet_at) into erfolgreich
    from public.chemie710_wartung_laeufe w where w.erfolg;

  -- Immer genau eine Zeile: „noch nie gelaufen" ist selbst ein Befund und
  -- soll im Dashboard sichtbar werden, nicht als leere Antwort verschwinden.
  return query select
    letzter.gestartet_at,
    erfolgreich,
    coalesce(letzter.erfolg, false),
    letzter.fehler,
    coalesce(letzter.ereignisse, 0::bigint),
    coalesce(letzter.fortschritt, 0::bigint),
    coalesce(letzter.tokens, 0::bigint),
    round(extract(epoch from now() - erfolgreich) / 86400.0, 1),
    -- Geplant ist ein wöchentlicher Lauf. Nach zehn Tagen ohne Erfolg ist
    -- etwas kaputt: pg_cron abgeschaltet, Fehler im Job, Projekt pausiert.
    coalesce(erfolgreich < now() - interval '10 days', true),
    (select count(*) from public.chemie710_wartung_laeufe w2
      where w2.gestartet_at > now() - interval '30 days');
end;
$fn$;

revoke all on function public.chemie710_wartung_status() from public, anon;
grant execute on function public.chemie710_wartung_status() to authenticated;


-- Auskunftsrecht: alles zu einer Person an einer Stelle.
create or replace function public.chemie710_person_export(kennung uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  erlaubt boolean := false;
  ergebnis jsonb;
begin
  if auth.role() = 'authenticated' or auth.uid() is not null then
    execute $q$
      select exists (
        select 1 from public.chemie710_teachers t where t.user_id = $1
      ) or coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'teacher', false)
    $q$ into erlaubt using auth.uid();
    if not erlaubt then
      raise exception 'Nur freigeschaltete Lehrkräfte dürfen Personendaten exportieren.'
        using errcode = '42501';
    end if;
  end if;

  select jsonb_build_object(
    'schueler',    (select to_jsonb(st) from public.chemie710_students st where st.id = kennung),
    'ereignisse',  (select coalesce(jsonb_agg(to_jsonb(e) order by e.ts), '[]'::jsonb)
                      from public.chemie710_events e where e.student_id = kennung),
    'fortschritt', (select coalesce(jsonb_agg(to_jsonb(pr)), '[]'::jsonb)
                      from public.chemie710_progress pr where pr.student_id = kennung),
    -- Auch Freigaben und Lernzeiten sind personenbezogen und gehoeren in
    -- eine Auskunft. Ein Export, der die Haelfte weglaesst, ist keiner.
    'freigaben',   (select coalesce(jsonb_agg(to_jsonb(fr) order by fr.freigegeben_at), '[]'::jsonb)
                      from public.chemie710_freigaben fr where fr.student_id = kennung),
    'lernzeit',    (select coalesce(jsonb_agg(to_jsonb(lz) order by lz.datum), '[]'::jsonb)
                      from public.chemie710_lernzeit lz where lz.student_id = kennung),
    -- Warm-up-Ergebnisse sind Bewertungsgrundlage. Gerade sie gehoeren in
    -- eine Auskunft: Wer nach ihnen benotet wird, darf sie sehen.
    'warmup',      (select coalesce(jsonb_agg(to_jsonb(wu) order by wu.datum, wu.id), '[]'::jsonb)
                      from public.chemie710_warmup_ergebnisse wu where wu.student_id = kennung)
  ) into ergebnis;
  return ergebnis;
end;
$$;


-- Löschrecht: Ereignisse, Fortschritt und Freigabeeintrag einer Person.
create or replace function public.chemie710_person_loeschen(kennung uuid)
returns table (tabelle text, geloescht bigint)
language plpgsql
security definer
set search_path = public
as $$
declare
  n_ereignisse bigint;
  n_fortschritt bigint;
  n_schueler bigint;
  erlaubt boolean := false;
begin
  if auth.role() = 'authenticated' or auth.uid() is not null then
    execute $q$
      select exists (
        select 1 from public.chemie710_teachers t where t.user_id = $1
      ) or coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'teacher', false)
    $q$ into erlaubt using auth.uid();
    if not erlaubt then
      raise exception 'Nur freigeschaltete Lehrkräfte dürfen Personendaten löschen.'
        using errcode = '42501';
    end if;
  end if;
  delete from public.chemie710_events where student_id = kennung;
  get diagnostics n_ereignisse = row_count;

  delete from public.chemie710_progress where student_id = kennung;
  get diagnostics n_fortschritt = row_count;

  delete from public.chemie710_students where id = kennung;
  get diagnostics n_schueler = row_count;

  return query
    select 'chemie710_events'::text, n_ereignisse
    union all
    select 'chemie710_progress'::text, n_fortschritt
    union all
    select 'chemie710_students'::text, n_schueler;
end;
$$;

