-- ------------------------------------------------------------
-- Warm-up-Ergebnis melden  (Aufruf mit Schueler-Token)
-- ------------------------------------------------------------
create or replace function public.chemie710_warmup_melden(
  p_aufgaben integer,
  p_richtig integer,
  p_reihe text default null,
  p_unit text default null,
  p_pfad text default null,
  p_dauer_s integer default 0,
  p_kategorien text[] default array[]::text[]
)
returns table (gewertet boolean, quote numeric, pflicht boolean)
language plpgsql
security definer
set search_path = public
as $fn$
declare
  kind uuid;
  aktuell public.chemie710_unterricht%rowtype;
  ist_pflicht boolean;
  wird_gewertet boolean;
  n_aufgaben smallint;
  n_richtig smallint;
begin
  kind := public.chemie710_token_student();
  if kind is null then
    raise exception 'Kein gueltiges Schueler-Sitzungstoken.' using errcode = '42501';
  end if;

  -- Werte werden gedeckelt, nicht geglaubt. Ein Aufruf mit 500 richtigen
  -- von 3 Aufgaben ist kein Ergebnis, sondern ein Angriff.
  n_aufgaben := least(greatest(coalesce(p_aufgaben, 0), 1), 20);
  n_richtig := least(greatest(coalesce(p_richtig, 0), 0), n_aufgaben);

  select * into aktuell from public.chemie710_unterricht where id = 1;
  ist_pflicht := aktuell.modus = 'bewertung'
    and (aktuell.gilt_bis is null or aktuell.gilt_bis > now());

  -- Gewertet wird nur der erste Pflichtlauf des Tages.
  wird_gewertet := ist_pflicht and not exists (
    select 1 from public.chemie710_warmup_ergebnisse w
    where w.student_id = kind
      and w.datum = (now() at time zone 'Europe/Berlin')::date
      and w.gewertet
  );

  begin
    insert into public.chemie710_warmup_ergebnisse
      (student_id, reihe, unit, pfad, aufgaben, richtig, dauer_s,
       kategorien, pflicht, gewertet)
    values
      (kind,
       nullif(lower(trim(coalesce(p_reihe, ''))), ''),
       nullif(lower(trim(coalesce(p_unit, ''))), ''),
       nullif(upper(trim(coalesce(p_pfad, ''))), ''),
       n_aufgaben, n_richtig,
       least(greatest(coalesce(p_dauer_s, 0), 0), 3600),
       coalesce(p_kategorien, array[]::text[]),
       ist_pflicht, wird_gewertet);
  exception when unique_violation then
    -- Zwei Geraete haben gleichzeitig gemeldet. Der zweite Lauf wird als
    -- Uebung gefuehrt, nicht verworfen.
    wird_gewertet := false;
    insert into public.chemie710_warmup_ergebnisse
      (student_id, reihe, unit, pfad, aufgaben, richtig, dauer_s,
       kategorien, pflicht, gewertet)
    values
      (kind,
       nullif(lower(trim(coalesce(p_reihe, ''))), ''),
       nullif(lower(trim(coalesce(p_unit, ''))), ''),
       nullif(upper(trim(coalesce(p_pfad, ''))), ''),
       n_aufgaben, n_richtig,
       least(greatest(coalesce(p_dauer_s, 0), 0), 3600),
       coalesce(p_kategorien, array[]::text[]),
       ist_pflicht, false);
  end;

  return query select
    wird_gewertet,
    round(n_richtig::numeric / n_aufgaben, 3),
    ist_pflicht;
end;
$fn$;

revoke all on function public.chemie710_warmup_melden(integer, integer, text, text, text, integer, text[]) from public;
grant execute on function public.chemie710_warmup_melden(integer, integer, text, text, text, integer, text[]) to anon, authenticated;


-- ------------------------------------------------------------
-- Lernmodus um das Warm-up erweitert
--
-- Der Rueckgabetyp aendert sich gegenueber V30; deshalb erst loeschen.
-- Die Anwendung liest hieraus, ob heute noch aufgewaermt werden muss.
-- ------------------------------------------------------------
drop function if exists public.chemie710_lernmodus();

create or replace function public.chemie710_lernmodus()
returns table (
  modus text,
  gilt_bis timestamptz,
  freigegeben text[],
  lernzeit_heute integer,
  warmup_pflicht boolean,
  warmup_heute boolean,
  bewertungsart text
)
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  kind uuid;
  aktuell public.chemie710_unterricht%rowtype;
  im_unterricht boolean;
begin
  kind := public.chemie710_token_student();
  if kind is null then
    raise exception 'Kein gueltiges Schueler-Sitzungstoken.' using errcode = '42501';
  end if;

  select * into aktuell from public.chemie710_unterricht where id = 1;

  -- Abgelaufener Bewertungsmodus gilt nicht mehr. Der Rueckfall ist der
  -- offene Zustand, nicht der gesperrte: Eine vergessene Umschaltung darf
  -- niemanden aussperren.
  im_unterricht := aktuell.modus = 'bewertung'
    and (aktuell.gilt_bis is null or aktuell.gilt_bis > now());

  return query select
    case when im_unterricht then 'bewertung' else 'uebung' end::text,
    aktuell.gilt_bis,
    coalesce((
      select array_agg(f.unit order by f.unit)
      from public.chemie710_freigaben f
      where f.student_id = kind
    ), array[]::text[]),
    coalesce((
      select sum(l.sekunden)::integer
      from public.chemie710_lernzeit l
      where l.student_id = kind
        and l.datum = (now() at time zone 'Europe/Berlin')::date
    ), 0),
    im_unterricht,
    exists (
      select 1 from public.chemie710_warmup_ergebnisse w
      where w.student_id = kind
        and w.datum = (now() at time zone 'Europe/Berlin')::date
        and w.gewertet
    ),
    coalesce((
      select s.bewertungsart from public.chemie710_students s where s.id = kind
    ), 'note')::text;
end;
$fn$;

revoke all on function public.chemie710_lernmodus() from public;
grant execute on function public.chemie710_lernmodus() to anon, authenticated;


