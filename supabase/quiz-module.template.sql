-- ============================================================
-- Einheitenquiz und benotungsrelevante Speicherung
-- ============================================================

begin;

create table if not exists public.chemie710_quiz_schluessel (
  unit text not null,
  pfad text not null,
  quiz_version integer not null,
  frage_id text not null,
  reihenfolge smallint not null,
  antwort jsonb not null,
  primary key (unit, pfad, quiz_version, frage_id),
  unique (unit, pfad, quiz_version, reihenfolge),
  constraint chemie710_quiz_schluessel_unit check (unit ~ '^[a-z]{2}-[0-9]{2}$'),
  constraint chemie710_quiz_schluessel_pfad check (pfad in ('A', 'B', 'C')),
  constraint chemie710_quiz_schluessel_version check (quiz_version >= 1),
  constraint chemie710_quiz_schluessel_reihenfolge check (reihenfolge between 1 and 3)
);

alter table public.chemie710_quiz_schluessel enable row level security;
revoke all on public.chemie710_quiz_schluessel from public, anon, authenticated;


create table if not exists public.chemie710_quiz_ergebnisse (
  id bigint generated by default as identity primary key,
  student_id uuid not null
    references public.chemie710_students(id) on delete cascade,
  unit text not null,
  pfad text not null,
  quiz_version integer not null,
  versuch smallint not null,
  fragen_ids text[] not null,
  antworten jsonb not null,
  aufgaben smallint not null,
  richtig smallint not null,
  dauer_s integer not null default 0,
  pflicht boolean not null default false,
  gewertet boolean not null default false,
  erstellt_at timestamptz not null default now(),
  constraint chemie710_quiz_ergebnis_unit check (unit ~ '^[a-z]{2}-[0-9]{2}$'),
  constraint chemie710_quiz_ergebnis_pfad check (pfad in ('A', 'B', 'C')),
  constraint chemie710_quiz_ergebnis_version check (quiz_version >= 1),
  constraint chemie710_quiz_ergebnis_versuch check (versuch >= 1),
  constraint chemie710_quiz_ergebnis_anzahl check (aufgaben = 3),
  constraint chemie710_quiz_ergebnis_richtig check (richtig between 0 and aufgaben),
  constraint chemie710_quiz_ergebnis_fragen check (cardinality(fragen_ids) = aufgaben),
  constraint chemie710_quiz_ergebnis_antworten check (jsonb_typeof(antworten) = 'array')
);

alter table public.chemie710_quiz_ergebnisse enable row level security;

create unique index if not exists chemie710_quiz_versuch_uidx
  on public.chemie710_quiz_ergebnisse
  (student_id, unit, pfad, quiz_version, versuch);

create unique index if not exists chemie710_quiz_ein_gewerteter_uidx
  on public.chemie710_quiz_ergebnisse
  (student_id, unit, pfad, quiz_version)
  where gewertet;

create index if not exists chemie710_quiz_uebersicht_idx
  on public.chemie710_quiz_ergebnisse (erstellt_at desc, student_id);

drop policy if exists "teachers read quiz results" on public.chemie710_quiz_ergebnisse;
create policy "teachers read quiz results"
on public.chemie710_quiz_ergebnisse for select to authenticated
using (public.chemie710_ist_lehrkraft());

revoke all on public.chemie710_quiz_ergebnisse from public, anon;
grant select on public.chemie710_quiz_ergebnisse to authenticated;


-- Die erwarteten Antworten bleiben in einer Tabelle ohne Data-API-Rechte.
-- Die Schüler-App sendet nur ihre Antworten; die Datenbank berechnet das
-- Ergebnis. Ein frei behaupteter Punktestand wird nicht angenommen.
-- __QUIZ_KEYS__


create or replace function public.chemie710_quiz_abgeben(
  p_unit text,
  p_pfad text,
  p_quiz_version integer,
  p_antworten jsonb,
  p_dauer_s integer default 0
)
returns table (
  ergebnis_id bigint,
  richtig integer,
  aufgaben integer,
  quote numeric,
  versuch integer,
  pflicht boolean,
  gewertet boolean
)
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  kind uuid;
  v_unit text := lower(trim(coalesce(p_unit, '')));
  v_pfad text := upper(trim(coalesce(p_pfad, '')));
  v_version integer := greatest(coalesce(p_quiz_version, 0), 0);
  v_aufgaben integer;
  v_gesendet integer;
  v_eindeutig integer;
  v_richtig integer;
  v_versuch integer;
  v_pflicht boolean;
  v_gewertet boolean;
  v_id bigint;
  v_klasse text;
  aktuell public.chemie710_unterricht%rowtype;
begin
  kind := public.chemie710_token_student();
  if kind is null then
    raise exception 'Kein gueltiges Schueler-Sitzungstoken.' using errcode = '42501';
  end if;

  if v_unit !~ '^[a-z]{2}-[0-9]{2}$' or v_pfad not in ('A', 'B', 'C') or v_version < 1 then
    raise exception 'Ungueltige Quizkennung.' using errcode = '22023';
  end if;
  if p_antworten is null or jsonb_typeof(p_antworten) <> 'array' then
    raise exception 'Antworten muessen als Liste gesendet werden.' using errcode = '22023';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_antworten) as a
     where jsonb_typeof(a) <> 'object' or not (a ? 'id') or not (a ? 'wert')
  ) then
    raise exception 'Jede Antwort braucht id und wert.' using errcode = '22023';
  end if;

  select count(*)::integer
    into v_aufgaben
    from public.chemie710_quiz_schluessel k
   where k.unit = v_unit and k.pfad = v_pfad and k.quiz_version = v_version;
  if v_aufgaben <> 3 then
    raise exception 'Der Fragenstand ist nicht vollstaendig eingerichtet.' using errcode = '22023';
  end if;

  select count(*)::integer, count(distinct a ->> 'id')::integer
    into v_gesendet, v_eindeutig
    from jsonb_array_elements(p_antworten) as a;
  if v_gesendet <> v_aufgaben or v_eindeutig <> v_aufgaben then
    raise exception 'Es muessen genau drei verschiedene Antworten gesendet werden.' using errcode = '22023';
  end if;
  if exists (
    select 1
      from jsonb_array_elements(p_antworten) as a
      left join public.chemie710_quiz_schluessel k
        on k.unit = v_unit and k.pfad = v_pfad and k.quiz_version = v_version
       and k.frage_id = a ->> 'id'
     where k.frage_id is null
  ) then
    raise exception 'Mindestens eine Frage gehoert nicht zu diesem Einheitenquiz.' using errcode = '22023';
  end if;

  select count(*)::integer
    into v_richtig
    from jsonb_array_elements(p_antworten) as a
    join public.chemie710_quiz_schluessel k
      on k.unit = v_unit and k.pfad = v_pfad and k.quiz_version = v_version
     and k.frage_id = a ->> 'id'
   where k.antwort = a -> 'wert';

  select * into aktuell from public.chemie710_unterricht where id = 1;
  select s.class_code into v_klasse from public.chemie710_students s where s.id = kind;
  v_pflicht := aktuell.modus = 'bewertung'
    and (aktuell.gilt_bis is null or aktuell.gilt_bis > now())
    and (aktuell.klasse is null or aktuell.klasse = v_klasse);

  perform pg_advisory_xact_lock(
    hashtextextended(kind::text || ':' || v_unit || ':' || v_pfad || ':' || v_version::text, 710)
  );
  select coalesce(max(q.versuch), 0) + 1
    into v_versuch
    from public.chemie710_quiz_ergebnisse q
   where q.student_id = kind and q.unit = v_unit and q.pfad = v_pfad
     and q.quiz_version = v_version;

  v_gewertet := v_pflicht and not exists (
    select 1 from public.chemie710_quiz_ergebnisse q
     where q.student_id = kind and q.unit = v_unit and q.pfad = v_pfad
       and q.quiz_version = v_version and q.gewertet
  );

  insert into public.chemie710_quiz_ergebnisse
    (student_id, unit, pfad, quiz_version, versuch, fragen_ids, antworten,
     aufgaben, richtig, dauer_s, pflicht, gewertet)
  select kind, v_unit, v_pfad, v_version, v_versuch,
         array_agg(k.frage_id order by k.reihenfolge),
         p_antworten, v_aufgaben, v_richtig,
         least(greatest(coalesce(p_dauer_s, 0), 0), 7200),
         v_pflicht, v_gewertet
    from public.chemie710_quiz_schluessel k
   where k.unit = v_unit and k.pfad = v_pfad and k.quiz_version = v_version
  returning id into v_id;

  return query select v_id, v_richtig, v_aufgaben,
    round(v_richtig::numeric / v_aufgaben, 3),
    v_versuch, v_pflicht, v_gewertet;
end;
$fn$;

revoke all on function public.chemie710_quiz_abgeben(text, text, integer, jsonb, integer)
  from public;
grant execute on function public.chemie710_quiz_abgeben(text, text, integer, jsonb, integer)
  to anon, authenticated;


create or replace function public.chemie710_quiz_uebersicht(
  p_klasse text default null,
  p_tage integer default 180
)
returns table (
  id bigint,
  student_id uuid,
  name text,
  klasse text,
  unit text,
  pfad text,
  quiz_version integer,
  versuch integer,
  richtig integer,
  aufgaben integer,
  quote numeric,
  note smallint,
  dauer_s integer,
  pflicht boolean,
  gewertet boolean,
  erstellt_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $fn$
  select q.id, q.student_id, s.display_name, s.class_code,
         upper(q.unit), q.pfad, q.quiz_version, q.versuch::integer,
         q.richtig::integer, q.aufgaben::integer,
         round(q.richtig::numeric / q.aufgaben, 3) as quote,
         case
           when not q.gewertet then null
           when q.richtig::numeric / q.aufgaben >= 0.92 then 1
           when q.richtig::numeric / q.aufgaben >= 0.81 then 2
           when q.richtig::numeric / q.aufgaben >= 0.67 then 3
           when q.richtig::numeric / q.aufgaben >= 0.50 then 4
           when q.richtig::numeric / q.aufgaben >= 0.30 then 5
           else 6
         end::smallint,
         q.dauer_s, q.pflicht, q.gewertet, q.erstellt_at
    from public.chemie710_quiz_ergebnisse q
    join public.chemie710_students s on s.id = q.student_id
   where public.chemie710_ist_lehrkraft()
     and s.active
     and (p_klasse is null or s.class_code = p_klasse)
     and q.erstellt_at >= now() - make_interval(days => least(greatest(coalesce(p_tage, 180), 1), 730))
   order by q.erstellt_at desc
   limit 500;
$fn$;

revoke all on function public.chemie710_quiz_uebersicht(text, integer) from public, anon;
grant execute on function public.chemie710_quiz_uebersicht(text, integer) to authenticated;


create or replace function public.chemie710_quiz_bewertung(
  p_klasse text default null,
  p_tage integer default 180
)
returns table (
  student_id uuid,
  name text,
  klasse text,
  quizze integer,
  aufgaben integer,
  richtig integer,
  quote numeric,
  note smallint,
  letzter_lauf timestamptz
)
language sql
stable
security definer
set search_path = ''
as $fn$
  with summen as (
    select q.student_id,
           count(*)::integer as quizze,
           sum(q.aufgaben)::integer as aufgaben,
           sum(q.richtig)::integer as richtig,
           max(q.erstellt_at) as letzter_lauf
      from public.chemie710_quiz_ergebnisse q
     where q.gewertet
       and q.erstellt_at >= now() - make_interval(days => least(greatest(coalesce(p_tage, 180), 1), 730))
     group by q.student_id
  ), bewertet as (
    select s.id, s.display_name, s.class_code,
           coalesce(x.quizze, 0) as quizze,
           coalesce(x.aufgaben, 0) as aufgaben,
           coalesce(x.richtig, 0) as richtig,
           case when x.aufgaben > 0 then round(x.richtig::numeric / x.aufgaben, 3) end as quote,
           x.letzter_lauf
      from public.chemie710_students s
      left join summen x on x.student_id = s.id
     where s.active and (p_klasse is null or s.class_code = p_klasse)
  )
  select b.id, b.display_name, b.class_code, b.quizze, b.aufgaben, b.richtig, b.quote,
         case
           when b.quote is null then null
           when b.quote >= 0.92 then 1
           when b.quote >= 0.81 then 2
           when b.quote >= 0.67 then 3
           when b.quote >= 0.50 then 4
           when b.quote >= 0.30 then 5
           else 6
         end::smallint,
         b.letzter_lauf
    from bewertet b
   where public.chemie710_ist_lehrkraft()
   order by b.display_name;
$fn$;

revoke all on function public.chemie710_quiz_bewertung(text, integer) from public, anon;
grant execute on function public.chemie710_quiz_bewertung(text, integer) to authenticated;


-- Bewertungsdaten muessen in der personenbezogenen Auskunft enthalten sein.
create or replace function public.chemie710_person_export(kennung uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  ergebnis jsonb;
begin
  if not public.chemie710_ist_lehrkraft() then
    raise exception 'Nur freigeschaltete Lehrkraefte duerfen Personendaten exportieren.'
      using errcode = '42501';
  end if;

  select jsonb_build_object(
    'schueler',    (select to_jsonb(st) from public.chemie710_students st where st.id = kennung),
    'ereignisse',  (select coalesce(jsonb_agg(to_jsonb(e) order by e.ts), '[]'::jsonb)
                      from public.chemie710_events e where e.student_id = kennung),
    'fortschritt', (select coalesce(jsonb_agg(to_jsonb(pr)), '[]'::jsonb)
                      from public.chemie710_progress pr where pr.student_id = kennung),
    'freigaben',   (select coalesce(jsonb_agg(to_jsonb(fr) order by fr.freigegeben_at), '[]'::jsonb)
                      from public.chemie710_freigaben fr where fr.student_id = kennung),
    'lernzeit',    (select coalesce(jsonb_agg(to_jsonb(lz) order by lz.datum), '[]'::jsonb)
                      from public.chemie710_lernzeit lz where lz.student_id = kennung),
    'warmup',      (select coalesce(jsonb_agg(to_jsonb(wu) order by wu.datum, wu.id), '[]'::jsonb)
                      from public.chemie710_warmup_ergebnisse wu where wu.student_id = kennung),
    'einheitenquiz', (select coalesce(jsonb_agg(to_jsonb(q) order by q.erstellt_at, q.id), '[]'::jsonb)
                        from public.chemie710_quiz_ergebnisse q where q.student_id = kennung)
  ) into ergebnis;
  return ergebnis;
end;
$fn$;

revoke all on function public.chemie710_person_export(uuid) from public, anon;
grant execute on function public.chemie710_person_export(uuid) to authenticated;

commit;
