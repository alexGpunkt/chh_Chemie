-- ============================================================
-- Einheitenquiz und benotungsrelevante Speicherung
-- ============================================================

begin;

create table if not exists public.chemie710_quiz_schluessel (
  unit text not null,
  pfad text not null,
  quiz_version integer not null,
  frage_id text not null,
  reihenfolge smallint not null,
  antwort jsonb not null,
  primary key (unit, pfad, quiz_version, frage_id),
  unique (unit, pfad, quiz_version, reihenfolge),
  constraint chemie710_quiz_schluessel_unit check (unit ~ '^[a-z]{2}-[0-9]{2}$'),
  constraint chemie710_quiz_schluessel_pfad check (pfad in ('A', 'B', 'C')),
  constraint chemie710_quiz_schluessel_version check (quiz_version >= 1),
  constraint chemie710_quiz_schluessel_reihenfolge check (reihenfolge between 1 and 3)
);

alter table public.chemie710_quiz_schluessel enable row level security;
revoke all on public.chemie710_quiz_schluessel from public, anon, authenticated;


create table if not exists public.chemie710_quiz_ergebnisse (
  id bigint generated by default as identity primary key,
  student_id uuid not null
    references public.chemie710_students(id) on delete cascade,
  unit text not null,
  pfad text not null,
  quiz_version integer not null,
  versuch smallint not null,
  fragen_ids text[] not null,
  antworten jsonb not null,
  aufgaben smallint not null,
  richtig smallint not null,
  dauer_s integer not null default 0,
  pflicht boolean not null default false,
  gewertet boolean not null default false,
  erstellt_at timestamptz not null default now(),
  constraint chemie710_quiz_ergebnis_unit check (unit ~ '^[a-z]{2}-[0-9]{2}$'),
  constraint chemie710_quiz_ergebnis_pfad check (pfad in ('A', 'B', 'C')),
  constraint chemie710_quiz_ergebnis_version check (quiz_version >= 1),
  constraint chemie710_quiz_ergebnis_versuch check (versuch >= 1),
  constraint chemie710_quiz_ergebnis_anzahl check (aufgaben = 3),
  constraint chemie710_quiz_ergebnis_richtig check (richtig between 0 and aufgaben),
  constraint chemie710_quiz_ergebnis_fragen check (cardinality(fragen_ids) = aufgaben),
  constraint chemie710_quiz_ergebnis_antworten check (jsonb_typeof(antworten) = 'array')
);

alter table public.chemie710_quiz_ergebnisse enable row level security;

create unique index if not exists chemie710_quiz_versuch_uidx
  on public.chemie710_quiz_ergebnisse
  (student_id, unit, pfad, quiz_version, versuch);

create unique index if not exists chemie710_quiz_ein_gewerteter_uidx
  on public.chemie710_quiz_ergebnisse
  (student_id, unit, pfad, quiz_version)
  where gewertet;

create index if not exists chemie710_quiz_uebersicht_idx
  on public.chemie710_quiz_ergebnisse (erstellt_at desc, student_id);

drop policy if exists "teachers read quiz results" on public.chemie710_quiz_ergebnisse;
create policy "teachers read quiz results"
on public.chemie710_quiz_ergebnisse for select to authenticated
using (public.chemie710_ist_lehrkraft());

revoke all on public.chemie710_quiz_ergebnisse from public, anon;
grant select on public.chemie710_quiz_ergebnisse to authenticated;


